"""Builds conformance/MATRIX.md from conformance/results/*.json and checks the expectations below.

Exits non-zero when an expectation fails, so CI catches a regression in any SDK.
Usage: python conformance/matrix.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
COLUMNS = [  # (results file, column label, role)
    ("js-17.2.1.json", "JS 17.2.1", "pre-fix"),
    ("js-17.4.0.json", "JS 17.4.0", "current"),
    ("go-v0.9.0.json", "Go v0.9.0", "current"),
    ("rust-30.0.0.json", "Rust stellar-xdr 30.0.0", "current"),
]
# Behaviour each sighting must show per column: the pre-fix tag reproduces the defect, current releases do not.
EXPECT = {
    "js-stellar-sdk#1789": {"JS 17.2.1": "defect", "JS 17.4.0": "ok", "Go v0.9.0": "n/a", "Rust stellar-xdr 30.0.0": "n/a"},
}


def cell(r):
    if r["decode"] != "ok":
        return "decode error"
    return "round-trips" if r["roundTripIdentical"] else "bytes change"


def main():
    runs = {label: (json.loads((HERE / "results" / f).read_text(encoding="utf-8")), role) for f, label, role in COLUMNS}
    labels = [label for _, label, _ in COLUMNS]
    failures = []

    lines = ["# Conformance matrix", "",
             "Generated by `conformance/matrix.py` from `conformance/results/`. Each corpus file is decoded with the "
             "SDK's own XDR types, re-encoded and compared byte for byte.", "",
             "## Corpus round trip", "", "| File | " + " | ".join(labels) + " |", "|" + " --- |" * (len(labels) + 1)]
    paths = [c["path"] for c in runs[labels[0]][0]["corpus"]]
    for p in paths:
        row = []
        for label in labels:
            data, role = runs[label]
            r = next(c for c in data["corpus"] if c["path"] == p)
            row.append(cell(r))
            if role == "current" and not r.get("roundTripIdentical"):
                failures.append(f"{label}: {p} does not round-trip ({r.get('error', 'bytes change')})")
        lines.append(f"| `{p.replace('corpus/entries/', '')}` | " + " | ".join(row) + " |")

    notes = sorted({c.get("error", "") for data, role in runs.values() if role == "pre-fix"
                    for c in data["corpus"] if c["decode"] != "ok"} - {""})
    if notes:
        lines += ["", "Pre-fix tags predate protocol 30, so they cannot read its ledger headers: " +
                  "; ".join(f"`{n}`" for n in notes)]

    lines += ["", "## Sightings", "", "| Sighting | " + " | ".join(labels) + " | Reproduced |", "|" + " --- |" * (len(labels) + 2)]
    for sid, expect in EXPECT.items():
        row = []
        for label in labels:
            v = next(x for x in runs[label][0]["vectors"] if x["sighting"] == sid)
            got = v.get("result", "n/a")
            row.append(got + (f" ({v['detail']})" if v.get("detail") and got != "n/a" else ""))
            if got != expect[label]:
                failures.append(f"{label}: {sid} is {got}, expected {expect[label]}")
        reproduced = all(next(x for x in runs[l][0]["vectors"] if x["sighting"] == sid).get("result") == expect[l] for l in labels)
        lines.append(f"| {sid} | " + " | ".join(row) + f" | {'yes' if reproduced else 'no'} |")

    (HERE / "MATRIX.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    if failures:
        sys.exit("\n".join(["", "EXPECTATION FAILURES:"] + failures))


if __name__ == "__main__":
    main()
